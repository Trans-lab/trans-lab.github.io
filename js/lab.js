(function () {
  'use strict';
  var D = window.TRANSLATIONS;
  var lang = 'en';
  try { lang = localStorage.getItem('translab.lang') === 'zh' ? 'zh' : 'en'; } catch (e) {}

  function t(key) {
    if (!D) return null;
    var cur = D[lang] || {}, en = D.en || {};
    if (Object.prototype.hasOwnProperty.call(cur, key)) return cur[key];
    if (Object.prototype.hasOwnProperty.call(en, key)) return en[key];
    return null; /* never expose the key */
  }

  function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = t(el.getAttribute('data-i18n'));
      if (v !== null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var v = t(el.getAttribute('data-i18n-placeholder'));
      if (v !== null) el.placeholder = v;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var v = t(el.getAttribute('data-i18n-aria'));
      if (v !== null) el.setAttribute('aria-label', v);
    });
    document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
    var btn = document.querySelector('.lang-btn');
    if (btn) {
      btn.textContent = lang === 'zh' ? 'EN' : '中文';
      btn.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切换到中文');
    }
    document.querySelectorAll('img[data-alt-zh]').forEach(function (el) {
      var v = lang === 'zh' ? el.getAttribute('data-alt-zh') : el.getAttribute('data-alt-en');
      if (v) el.alt = v;
    });
    document.querySelectorAll('a[data-pdf-title]').forEach(function (a) {
      var t = a.getAttribute('data-pdf-title');
      a.setAttribute('aria-label', lang === 'zh' ? ('PDF：' + t + '（在新窗口打开）') : ('PDF: ' + t + ' (opens in a new tab)'));
    });
    document.querySelectorAll('[data-swap]').forEach(function (el) {
      var v = lang === 'zh' ? el.getAttribute('data-zh') : el.getAttribute('data-en');
      if (v) el.textContent = v;
    });
    if (document.body && document.body.dataset && document.body.dataset.titleEn) {
      document.title = lang === 'zh' ? document.body.dataset.titleZh : document.body.dataset.titleEn;
    }
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
  }

  window.TR = { t: t, lang: function () { return lang; }, setLang: function (n) { lang = n; try { localStorage.setItem('translab.lang', n); } catch (e) {} applyLanguage(); } };

  document.addEventListener('DOMContentLoaded', function () {
    var btn = document.querySelector('.lang-btn');
    if (btn) btn.addEventListener('click', function () { window.TR.setLang(lang === 'zh' ? 'en' : 'zh'); });

    var toggle = document.querySelector('.menu-toggle');
    var nav = document.querySelector('.nav');
    if (toggle && nav) {
      toggle.addEventListener('click', function () {
        var open = !nav.classList.contains('open');
        nav.classList.toggle('open', open);
        toggle.setAttribute('aria-expanded', String(open));
        var lbl = open ? t('menu.close') : t('menu.open');
        if (lbl !== null) toggle.setAttribute('aria-label', lbl);
      });
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape' && nav.classList.contains('open')) {
          nav.classList.remove('open');
          toggle.setAttribute('aria-expanded', 'false');
          var lbl = t('menu.open');
          if (lbl !== null) toggle.setAttribute('aria-label', lbl);
          toggle.focus();
        }
      });
    }

    var search = document.getElementById('pubSearch');
    if (search) {
      var yearSel = document.getElementById('pubYear');
      var pdfBox = document.getElementById('pubPdf');
      var typeBtns = Array.prototype.slice.call(document.querySelectorAll('[data-type-btn]'));
      var items = Array.prototype.slice.call(document.querySelectorAll('.pub-card'));
      var countEl = document.getElementById('pubCount');
      var emptyEl = document.getElementById('pubEmpty');
      var sections = Array.prototype.slice.call(document.querySelectorAll('.pub-section'));
      var groups = Array.prototype.slice.call(document.querySelectorAll('.year-group'));
      var activeType = 'all';
      var fmt = function (n, total) {
        return lang === 'zh' ? ('显示 ' + n + ' / ' + total + ' 条') : ('Showing ' + n + ' of ' + total + ' records');
      };
      var run = function () {
        var q = search.value.toLocaleLowerCase().trim();
        var year = yearSel ? yearSel.value : 'all';
        var pdf = pdfBox ? pdfBox.checked : false;
        var shown = 0;
        items.forEach(function (it) {
          var ok = (activeType === 'all' || it.getAttribute('data-type') === activeType) &&
            (year === 'all' || it.getAttribute('data-year') === year) &&
            (!pdf || it.querySelector('a[data-pdf]') !== null) &&
            (q === '' || it.textContent.toLocaleLowerCase().indexOf(q) !== -1);
          it.hidden = !ok;
          if (ok) shown += 1;
        });
        groups.forEach(function (g) {
          g.hidden = !Array.prototype.some.call(g.querySelectorAll('.pub-card'), function (x) { return !x.hidden; });
        });
        sections.forEach(function (s) {
          s.hidden = !Array.prototype.some.call(s.querySelectorAll('.pub-card'), function (x) { return !x.hidden; });
        });
        if (countEl) countEl.textContent = fmt(shown, items.length);
        if (emptyEl) emptyEl.hidden = shown !== 0;
      };
      typeBtns.forEach(function (b) {
        b.addEventListener('click', function () {
          activeType = b.getAttribute('data-type-btn');
          typeBtns.forEach(function (x) { x.setAttribute('aria-pressed', String(x === b)); });
          run();
        });
      });
      search.addEventListener('input', run);
      if (yearSel) yearSel.addEventListener('change', run);
      if (pdfBox) pdfBox.addEventListener('change', run);
      var reset = document.getElementById('pubReset');
      if (reset) reset.addEventListener('click', function () {
        search.value = '';
        if (yearSel) yearSel.value = 'all';
        if (pdfBox) pdfBox.checked = false;
        var all = document.querySelector('[data-type-btn="all"]');
        if (all) all.click();
        search.focus();
      });
      document.addEventListener('langchange', run);
      run();

      var fToggle = document.querySelector('.toolbar .filters-toggle');
      if (fToggle) fToggle.addEventListener('click', function () {
        var inner = document.querySelector('.toolbar-inner');
        inner.classList.toggle('more');
        fToggle.setAttribute('aria-expanded', String(inner.classList.contains('more')));
      });
    }

    var resSearch = document.getElementById('resSearch');
    if (resSearch) {
      var resItems = Array.prototype.slice.call(document.querySelectorAll('.res-card2'));
      var cats = Array.prototype.slice.call(document.querySelectorAll('.res-cat'));
      var resCount = document.getElementById('resCount');
      var rrun = function () {
        var q = resSearch.value.toLocaleLowerCase().trim();
        var n = 0;
        resItems.forEach(function (it) {
          var ok = q === '' || it.textContent.toLocaleLowerCase().indexOf(q) !== -1;
          it.hidden = !ok;
          if (ok) n += 1;
        });
        cats.forEach(function (c) {
          c.hidden = !Array.prototype.some.call(c.querySelectorAll('.res-card2'), function (x) { return !x.hidden; });
        });
        if (resCount) resCount.textContent = lang === 'zh' ? ('显示 ' + n + ' / ' + resItems.length + ' 项') : ('Showing ' + n + ' of ' + resItems.length + ' resources');
      };
      resSearch.addEventListener('input', rrun);
      document.addEventListener('langchange', rrun);
      rrun();
    }

    /* citation dialog */
    var citeDlg = document.getElementById('citeDialog');
    if (citeDlg) {
      var citeText = document.getElementById('citeText');
      var citeBtns = Array.prototype.slice.call(citeDlg.querySelectorAll('[data-cite-style]'));
      var citeCopy = document.getElementById('citeCopy');
      var citeCurrent = null, citeStyle = 'apa', copyTimer = null;
      var renderCite = function () {
        if (citeCurrent) citeText.textContent = citeCurrent.getAttribute('data-cite-' + citeStyle) || '';
      };
      var setCopyLabel = function (k) {
        if (citeCopy) citeCopy.textContent = t(k) || citeCopy.textContent;
      };
      document.addEventListener('click', function (e) {
        var b = e.target.closest ? e.target.closest('.cite-btn') : null;
        if (!b) return;
        citeCurrent = b;
        citeStyle = 'apa';
        citeBtns.forEach(function (x) {
          var on = x.getAttribute('data-cite-style') === 'apa';
          x.setAttribute('aria-pressed', String(on));
          x.classList.toggle('active', on);
        });
        renderCite();
        setCopyLabel('pubs.cite.copy');
        if (!citeDlg.open) citeDlg.showModal();
      });
      citeBtns.forEach(function (x) {
        x.addEventListener('click', function () {
          citeStyle = x.getAttribute('data-cite-style');
          citeBtns.forEach(function (y) {
            y.setAttribute('aria-pressed', String(y === x));
            y.classList.toggle('active', y === x);
          });
          renderCite();
          setCopyLabel('pubs.cite.copy');
        });
      });
      if (citeCopy) citeCopy.addEventListener('click', function () {
        var txt = citeText.textContent || '';
        var done = function () {
          citeCopy.textContent = t('pubs.cite.copied') || 'Copied';
          clearTimeout(copyTimer);
          copyTimer = setTimeout(function () { setCopyLabel('pubs.cite.copy'); }, 1600);
        };
        var fallback = function () {
          var ta = document.createElement('textarea');
          ta.value = txt;
          ta.setAttribute('readonly', '');
          ta.style.position = 'fixed'; ta.style.opacity = '0';
          document.body.appendChild(ta);
          ta.select();
          try { document.execCommand('copy'); } catch (err) {}
          document.body.removeChild(ta);
          done();
        };
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(txt).then(done, fallback);
        } else { fallback(); }
      });
      var citeClose = document.getElementById('citeClose');
      if (citeClose) citeClose.addEventListener('click', function () { citeDlg.close(); });
      citeDlg.addEventListener('click', function (e) { if (e.target === citeDlg) citeDlg.close(); });
      document.addEventListener('langchange', function () { setCopyLabel('pubs.cite.copy'); });
    }

    applyLanguage();
  });
})();
